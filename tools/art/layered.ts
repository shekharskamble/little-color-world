// Writes code-generated pages as Inkscape-convention SVGs (docs/ARTWORK_PIPELINE.md) and imports them.
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

export const ROOT = resolve(__dirname, '../..');
export const W = 1024;
export const H = 768;
export const INK = '#1e1b2e';

/** A fillable region: an element from ./primitives plus its name. It is written white, as children first see it.
 *  `outline: false` leaves it unstroked (e.g. ground whose edges are the page edges). */
export type Region = { name: string; el: string; outline?: false };
export type GeneratedPage = {
  id: string;
  title: string;
  subtitle?: string;
  age: '2-3' | '4-5';
  /** Paint order: later regions sit on top. A full-page background region is added underneath. */
  regions: Region[];
  /** Complete locked, pre-coloured elements (eyes, cheeks). */
  details: string[];
  /** Extra lines (smiles, whiskers): path data, optionally with a transform (a character drawn bigger). */
  lines: Array<string | { d: string; transform: string }>;
};

export function layeredSvg(p: GeneratedPage, source: { theme: string; generator: string }): string {
  const region = (s: Region) => `    ${s.el.replace(/^<(\w+)/, `<$1 inkscape:label="${s.name}"`)} style="fill:#ffffff${s.outline === false ? ';stroke:none' : ''}" />`;
  return `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<!-- ${p.title} (${source.theme}). Generated by ${source.generator}; edit there and re-run. Layer convention: docs/ARTWORK_PIPELINE.md. -->
<svg
   xmlns="http://www.w3.org/2000/svg"
   xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape"
   xmlns:sodipodi="http://sodipodi.sourceforge.net/DTD/sodipodi-0.dtd"
   width="${W}"
   height="${H}"
   viewBox="0 0 ${W} ${H}"
   version="1.1">
  <g inkscape:groupmode="layer" id="regions" inkscape:label="regions" style="stroke:${INK};stroke-width:10;stroke-linejoin:round;stroke-linecap:round">
    <rect inkscape:label="background" x="0" y="0" width="${W}" height="${H}" style="fill:#ffffff;stroke:none" />
${p.regions.map(region).join('\n')}
  </g>
  <g inkscape:groupmode="layer" id="details" inkscape:label="details" style="stroke:none">
${p.details.map((d) => `    ${d}`).join('\n')}
  </g>
  <g inkscape:groupmode="layer" id="outline" inkscape:label="outline" style="fill:none;stroke:${INK};stroke-width:10;stroke-linecap:round;stroke-linejoin:round">
${p.lines.map((l, i) => typeof l === 'string' ? `    <path inkscape:label="line-${i + 1}" d="${l}" />` : `    <path inkscape:label="line-${i + 1}" d="${l.d}" transform="${l.transform}" />`).join('\n')}
  </g>
</svg>
`;
}

const flag = (name: string) => {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
};

/**
 * Writes each page to `outDir/<id>.svg`; with `--import` on the command line, imports it into `themeId`. Exits 1 on failure.
 * `--only a,b` limits it to pages whose id contains one of the words. `--out <dir>` writes there instead and never imports
 * (for trying out a style without changing the app).
 */
export function writePages(pages: GeneratedPage[], outDir: string, themeId: string, source: { theme: string; generator: string }): void {
  const only = flag('--only')?.split(',');
  const out = flag('--out');
  if (out) outDir = resolve(out);
  mkdirSync(outDir, { recursive: true });
  const doImport = process.argv.includes('--import') && !out;
  let failed = 0;
  for (const p of pages.filter((pg) => !only || only.some((w) => pg.id.includes(w)))) {
    const file = join(outDir, `${p.id}.svg`);
    writeFileSync(file, layeredSvg(p, source));
    if (!doImport) {
      console.log(`wrote ${p.id}.svg`);
      continue;
    }
    const args = ['tsx', 'tools/lcw/cli.ts', 'page', 'import', file, '--theme', themeId, '--title', p.title, '--age', p.age];
    if (p.subtitle) args.push('--subtitle', p.subtitle);
    // Regenerating art can rename regions; only allowed when asked (saved colorings refer to region ids).
    if (process.argv.includes('--allow-removed')) args.push('--allow-removed');
    try {
      execFileSync('npx', args, { cwd: ROOT, stdio: 'inherit' });
    } catch {
      failed++;
    }
  }
  if (failed) {
    console.error(`${failed} page(s) failed to import`);
    process.exit(1);
  }
}
